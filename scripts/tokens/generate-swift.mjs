#!/usr/bin/env node
/**
 * Token bridge for the tvOS app (PHASE-4-TV-PLAN §2.2 A1).
 *
 *   node scripts/tokens/generate-swift.mjs            # rewrite the generated Swift
 *   node scripts/tokens/generate-swift.mjs --check    # exit 1 if it is out of date (CI)
 *   [--out <file>]                                    # another target (tests)
 *
 * Inputs, both vendored and pinned by sha256 below:
 *   Tokens/fiestaui-tokens.json  @fiestaboard/ui `tokens.json` (W3C DTCG), built
 *                                by FiestaUI's own scripts/tokens/extract-tokens.mjs
 *                                from alpha. Replaced by the published package's
 *                                file once an alpha is on npm, or by FiestaUI G6.
 *   Tokens/platform-tv.json      Figma "Platform · TV" variables (149:182577).
 *
 * Output: Sources/Core/Generated/FiestaTokens+Generated.swift. It lives in
 * Core, not UI, because the board pigments (`BoardColor`, Core) read it, and
 * it imports Foundation only, so check-layering.sh still holds. UI code reads
 * it through `Fiesta.palette` / `Fiesta.Colors` and `PlatformTV`.
 *
 * To update: replace an input, update its sha256 here, run without --check,
 * commit both.
 */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const INPUTS = {
  tokens: {
    path: "Tokens/fiestaui-tokens.json",
    sha256: "2e536f7582e09fdcb88a7f33fe8db4523efe5c025cf79b81d39159e22f81f01b",
    fiestauiRef: "alpha",
    fiestauiCommit: "a84531f5ad3e88095ca001b03aa6d1afe54601f6",
  },
  platformTV: {
    path: "Tokens/platform-tv.json",
    sha256: "499325c635d773ad2186df540a5a8aee5e6a7411de6839aafd6f4dfd9c5d10aa",
  },
};
export const OUTPUT = "Sources/Core/Generated/FiestaTokens+Generated.swift";

/** kebab-case → lowerCamelCase */
export function swiftName(name) {
  return name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
}

const num = (v) => {
  const s = Number(v.toFixed(4)).toString();
  return s.includes(".") || s.includes("e") ? s : s;
};

function colourGroup(title, group, doc) {
  const names = Object.keys(group).filter((k) => !k.startsWith("$") && group[k]?.$type === "color");
  const lines = [`    /// ${doc}`, `    public enum ${title} {`];
  for (const name of names) {
    const v = group[name].$value;
    const [r, g, b] = v.components;
    lines.push(
      `        public static let ${swiftName(name)} = TokenColor(hex: "${v.hex.toLowerCase()}", red: ${num(r)}, green: ${num(g)}, blue: ${num(b)}, alpha: ${num(v.alpha ?? 1)})`,
    );
  }
  lines.push("", "        /// Every colour in this group, by its FiestaUI token name.");
  lines.push("        public static let all: [String: TokenColor] = [");
  for (const name of names) lines.push(`            "${name}": ${swiftName(name)},`);
  lines.push("        ]", "    }");
  return lines;
}

function dimensionGroup(title, group, doc, unitName) {
  const lines = [`    /// ${doc}`, `    public enum ${title} {`];
  for (const [name, token] of Object.entries(group)) {
    if (name.startsWith("$") || token?.$type !== "dimension") continue;
    lines.push(`        public static let ${swiftName(name)}: Double = ${num(token.$value.value)} // ${unitName}`);
  }
  lines.push("    }");
  return lines;
}

function durationGroup(group) {
  const lines = ["    /// Motion durations, in seconds.", "    public enum Duration {"];
  for (const [name, token] of Object.entries(group)) {
    if (name.startsWith("$") || token?.$type !== "duration") continue;
    lines.push(`        public static let ${swiftName(name)}: Double = ${num(token.$value.value / 1000)}`);
  }
  lines.push("    }");
  return lines;
}

/** @param {string} root repository root */
export function generate(root) {
  const read = (p) => readFileSync(path.join(root, p));
  const tokensBytes = read(INPUTS.tokens.path);
  const tvBytes = read(INPUTS.platformTV.path);
  const sha = (b) => createHash("sha256").update(b).digest("hex");
  const tokens = JSON.parse(tokensBytes.toString("utf8"));
  const tv = JSON.parse(tvBytes.toString("utf8"));
  const meta = tokens.$extensions?.["app.fiestaboard"] ?? {};
  const tvMeta = tv.$extensions?.["app.fiestaboard"] ?? {};

  const out = [
    "// GENERATED by scripts/tokens/generate-swift.mjs. Do not edit by hand.",
    `// ${INPUTS.tokens.path}: ${meta.package} ${meta.version}, FiestaUI ${INPUTS.tokens.fiestauiRef} ${INPUTS.tokens.fiestauiCommit}`,
    `//   sha256 ${sha(tokensBytes)}`,
    `// ${INPUTS.platformTV.path}: Figma ${tvMeta.collectionName} ${tvMeta.collection}, exported ${tvMeta.exportedAt}`,
    `//   sha256 ${sha(tvBytes)}`,
    "",
    "import Foundation",
    "",
    "/// One sRGB token colour. Components are 0–1; `hex` ignores alpha.",
    "public struct TokenColor: Equatable, Sendable {",
    "    public let hex: String",
    "    public let red: Double",
    "    public let green: Double",
    "    public let blue: Double",
    "    public let alpha: Double",
    "",
    "    public init(hex: String, red: Double, green: Double, blue: Double, alpha: Double) {",
    "        self.hex = hex",
    "        self.red = red",
    "        self.green = green",
    "        self.blue = blue",
    "        self.alpha = alpha",
    "    }",
    "}",
    "",
    "/// FiestaUI design tokens (`@fiestaboard/ui` tokens.json).",
    "public enum FiestaTokenValues {",
    ...colourGroup("Dark", tokens.color.dark, "`color.dark.*`: the theme the TV app uses."),
    "",
    ...colourGroup("Light", tokens.color.light, "`color.light.*`, generated for completeness and for the phone apps' bridge."),
    "",
    ...colourGroup("Board", tokens.board, "`board.*`: split-flap pigments and board surfaces."),
    "",
    ...dimensionGroup("Radius", tokens.radius, "`radius.*`, in CSS px (= pt).", "px"),
    "",
    ...durationGroup(tokens.motion.duration),
    "}",
    "",
    "/// Figma \"Platform · TV\" values for tvOS, in pt at 1920×1080.",
    "public enum PlatformTVValues {",
    ...dimensionGroup("TVOS", tv.tv.tvos, "`tv/tvos/*`", "pt").slice(2, -1).map((l) => l.replace(/^ {4}/, "")),
    `    public static let focusOutline: Double = ${num(tv.tv.focus.outline.$value.value)} // pt, \`tv/focus/outline\``,
    "}",
    "",
  ];
  return out.join("\n");
}

function main(argv) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
  let check = false;
  let outFile = path.join(root, OUTPUT);
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--check") check = true;
    else if (argv[i] === "--out") outFile = path.resolve(argv[++i]);
    else throw new Error(`unknown argument: ${argv[i]}`);
  }
  const sha = (p) => createHash("sha256").update(readFileSync(path.join(root, p))).digest("hex");
  for (const input of Object.values(INPUTS)) {
    if (sha(input.path) !== input.sha256) {
      throw new Error(`${input.path} does not match its pinned sha256; update INPUTS deliberately`);
    }
  }
  const swift = generate(root);
  if (check) {
    let current = "";
    try {
      current = readFileSync(outFile, "utf8");
    } catch {}
    if (current !== swift) {
      process.stderr.write(`${path.relative(root, outFile)} is out of date: run node scripts/tokens/generate-swift.mjs\n`);
      return 1;
    }
    process.stdout.write("Generated tokens are up to date.\n");
    return 0;
  }
  mkdirSync(path.dirname(outFile), { recursive: true });
  writeFileSync(outFile, swift);
  process.stdout.write(`Wrote ${path.relative(root, outFile)}\n`);
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (error) {
    process.stderr.write(`generate-swift: ${error.message}\n`);
    process.exitCode = 2;
  }
}
